test('アウトラインから子と兄弟を追加し、その場編集・Undo・再読込できる', async ({ page }) => {
  const id = await create(page);
  await page.getByRole('button', { name: '☷ アウトライン', exact: true }).click();
  const outline = page.locator('.outline');
  await outline.getByRole('button', { name: '＋ 子を追加', exact: true }).click();
  const input = outline.getByRole('textbox', { name: 'アウトラインのトピック本文' });
  await expect(input).toBeFocused();
  await input.fill('アウトラインの子'); await input.press('Enter');
  await outline.getByRole('button', { name: '＋ 兄弟を追加', exact: true }).click();
  await expect(input).toBeFocused();
  await input.dispatchEvent('compositionstart'); await input.fill('アウトラインの兄弟');
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true });
  await expect(input).toBeVisible(); await input.dispatchEvent('compositionend'); await input.press('Enter'); await saved(page);
  let document = await (await page.request.get(`/api/maps/${id}`)).json();
  expect(document.nodes[document.rootId].childIds).toHaveLength(2);
  await page.getByRole('button', { name: '元に戻す', exact: true }).click(); await saved(page);
  document = await (await page.request.get(`/api/maps/${id}`)).json();
  expect(document.nodes[document.rootId].childIds).toHaveLength(1);
  await page.getByRole('button', { name: 'やり直す', exact: true }).click(); await saved(page);
  await page.reload();
  document = await (await page.request.get(`/api/maps/${id}`)).json();
  const texts = document.nodes[document.rootId].childIds.map((nodeId: string) => document.nodes[nodeId].text);
  expect(texts).toEqual(['アウトラインの子','アウトラインの兄弟']);
  await page.getByRole('button', { name: '☷ アウトライン', exact: true }).click();
  await outline.getByRole('treeitem', { name: 'アウトラインの子', exact: true }).click();
  await page.getByRole('button', { name: 'アウトラインを閉じる' }).click();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('textbox', { name: 'トピック本文', exact: true })).toBeFocused();
  await page.getByRole('textbox', { name: 'トピック本文', exact: true }).press('Escape');
});
test('専用JSON形式のクリップボードは再読込後も配下を貼り付けられる', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  const id = await create(page);
  await page.keyboard.press('Tab');
  const input = page.getByRole('textbox', { name: 'トピック本文', exact: true });
  await input.fill('コピーする枝'); await input.press('Enter');
  await page.getByRole('textbox', { name: 'トピックのメモ' }).fill('コピーのメモ'); await saved(page);
  await page.getByRole('button', { name: 'コピー', exact: true }).click();
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('コピーする枝');
  const clipboardTypes = await page.evaluate(async () => (await navigator.clipboard.read()).flatMap(item => item.types));
  expect(clipboardTypes).toContain('web application/x-mindmap+json');
  await page.reload();
  await page.getByRole('button', { name: '貼り付け', exact: true }).click();
  await expect(page.locator('.topic')).toHaveCount(3); await saved(page);
  const document = await (await page.request.get(`/api/maps/${id}`)).json();
  const pasted = Object.values(document.nodes).filter((node: any) => node.text === 'コピーする枝') as any[];
  expect(pasted).toHaveLength(2); expect(pasted.every(node => node.note === 'コピーのメモ')).toBe(true);
});
